                            <span class="text-[10px] font-mono text-slate-400">NPSN: ${item.npsn}</span>
                        </div>
                        <div class="text-xs font-black text-slate-900 leading-snug">${item.name}</div>
                        <div class="text-[11px] text-slate-500 font-medium">
                            <i class="fa-solid fa-location-dot text-rose-500 mr-1"></i>Kecamatan ${item.kecamatan}, Kab. Boyolali
                        </div>
                        <div class="pt-1.5 mt-1.5 border-t border-slate-100 flex items-center justify-between">
                            <div>
                                <div class="text-[10px] text-slate-400">Pendaftar Real-time</div>
                                <div class="text-xs font-black ${item.count > 0 ? 'text-emerald-600' : 'text-slate-700'}">
                                    ${item.count} Calon Siswa
                                </div>
                            </div>
                            <a href="${studentListBaseUrl}&search=${encodeURIComponent(item.name)}"
                               class="px-2.5 py-1 rounded-lg bg-sky-600 hover:bg-sky-700 text-white text-[10px] font-bold transition">
                                Lihat Data
                            </a>
                        </div>
                    </div>
                `;

                const marker = L.marker([item.lat, item.lng], {
                    icon: customIcon,
                    zIndexOffset: hasRegistrants ? 500 + item.count : 100
                }).bindPopup(popupHtml);

                marker.addTo(markersLayerGroup);
                schoolMarkersByName[item.name] = marker;
            });
        }

