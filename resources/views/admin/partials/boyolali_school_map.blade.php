        window.handleBoyolaliMapSearch = function(query) {
            const q = (query || '').trim().toLowerCase();
            const clearBtn = document.getElementById('boyolali-map-search-clear');
            const resultsBox = document.getElementById('boyolali-map-search-results');

            if (clearBtn) {
                clearBtn.classList.toggle('hidden', q === '');
                clearBtn.classList.toggle('flex', q !== '');
            }

            renderBoyolaliMarkers(q);

            if (!resultsBox) return;
            if (q === '') {
                resultsBox.classList.add('hidden');
                resultsBox.innerHTML = '';
                return;
            }

            const matches = boyolaliSchoolsData.filter(item =>
                `${item.name} ${item.kecamatan} ${item.npsn}`.toLowerCase().includes(q)
            ).slice(0, 8);

            if (matches.length === 0) {
                resultsBox.innerHTML = `<div class="p-3 text-slate-400 text-center">Sekolah / NPSN tidak ditemukan di Kabupaten Boyolali.</div>`;
                resultsBox.classList.remove('hidden');
                return;
            }

            resultsBox.innerHTML = matches.map(m => `
                <button type="button"
                        onclick="selectBoyolaliSearchSchool(${m.lat}, ${m.lng}, '${m.name.replace(/'/g, "\\'")}')"
                        class="w-full text-left px-3.5 py-2.5 hover:bg-sky-50 transition flex items-center justify-between gap-2 cursor-pointer">
                    <div class="truncate">
                        <div class="font-bold text-slate-800 truncate">${m.name}</div>
                        <div class="text-[10px] text-slate-400">Kec. ${m.kecamatan} &bull; NPSN ${m.npsn}</div>
                    </div>
                    <span class="px-2 py-0.5 rounded-full text-[10px] font-extrabold ${m.count > 0 ? 'bg-emerald-100 text-emerald-800' : 'bg-slate-100 text-slate-600'} shrink-0">
                        ${m.count > 0 ? m.count + ' siswa' : 'Sasaran'}
                    </span>
                </button>
            `).join('');
            resultsBox.classList.remove('hidden');
        };

        window.selectBoyolaliSearchSchool = function(lat, lng, name) {
            const resultsBox = document.getElementById('boyolali-map-search-results');
            if (resultsBox) {
                resultsBox.classList.add('hidden');
            }
            window.focusBoyolaliSchool(lat, lng, name);
        };

        window.clearBoyolaliMapSearch = function() {
            const input = document.getElementById('boyolali-map-search-input');
            if (input) {
                input.value = '';
            }
            window.handleBoyolaliMapSearch('');
            window.resetBoyolaliMapView();
        };

        async function syncBoyolaliMapRealtime() {
            try {
                const res = await fetch(@json(route('spmb.map.realtime')), {
                    headers: { 'Accept': 'application/json' }
                });
                if (!res.ok) return;
                const data = await res.json();
                if (!data || !data.school_counts) return;

                let activeCount = 0;
                boyolaliSchoolsData.forEach(item => {
                    const normKey = item.name.trim().toUpperCase();
                    if (typeof data.school_counts[normKey] !== 'undefined') {
                        item.count = parseInt(data.school_counts[normKey], 10) || 0;
                    }
                    if (item.count > 0) activeCount++;
                });

                const regEl = document.getElementById('boyolali-live-registrants-count');
                if (regEl && typeof data.total_registrations !== 'undefined') {
                    regEl.textContent = Number(data.total_registrations).toLocaleString('id-ID');
                }
                const actEl = document.getElementById('boyolali-live-active-schools');
                if (actEl) {
                    actEl.textContent = Math.max(activeCount, data.active_schools_count || 0);
                }

                const searchInput = document.getElementById('boyolali-map-search-input');
                renderBoyolaliMarkers(searchInput ? searchInput.value : '');
            } catch (e) {
                // Silent fail on background poll
            }
        }

        document.addEventListener('DOMContentLoaded', function() {
            setTimeout(initBoyolaliTargetMap, 80);
            setInterval(syncBoyolaliMapRealtime, 20000);
        });
    })();
